SET NAMES utf8mb4;

CREATE TABLE kanji_entries (
    id BIGINT NOT NULL AUTO_INCREMENT,
    character_text VARCHAR(10) NOT NULL,
    stroke_count INT NOT NULL,
    jlpt_level VARCHAR(20) NULL,
    han_viet VARCHAR(100) NOT NULL,
    on_readings VARCHAR(255) NULL,
    kun_readings VARCHAR(255) NULL,
    meaning TEXT NOT NULL,
    radicals VARCHAR(50) NULL,
    frequency_rank INT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT uk_kanji_character UNIQUE (character_text),
    INDEX idx_kanji_character (character_text)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

